/**
 * JEV client — the simplest possible interface to local AI decisions.
 *
 * Two transports, one API:
 *   native: open-jev runs in-process (ARM64 Mac / Linux)
 *   http:   Docker container on x64 Mac or remote server
 *
 * mode: "auto" tries native first, falls back to HTTP.
 */

import { Value } from "@sinclair/typebox/value";
import { existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import type { Answer, Question, JevConfig, ModelInfo, ModelAlias } from "./schemas.js";
import { DecideRequestSchema, DecideResponseSchema } from "./schemas.js";
import { LOCAL_MODELS, REMOTE_MODELS } from "./models.generated.js";

// ─── Model registry (mirrors open-jev's MODELS) ────────────────────

const MODEL_REPOS: Record<string, string> = {
  "kev-0.6b": "onnx-community/kev-0.6b-ONNX",
  "kev-4b": "onnx-community/kev-4b-ONNX",
  "open-jev": "onnx-community/open-jev-deberta-v3-large-ONNX",
};

const MODEL_SIZES: Record<string, number> = {
  "kev-0.6b": 383_111_829,
  "kev-4b": 2_528_556_269,
  "open-jev": 838_860_800,
};

const MODEL_DISPLAY_NAMES: Record<string, string> = {
  "kev-0.6b": "Kev 0.6B — fast default",
  "kev-4b": "Kev 4B — accuracy ceiling",
  "open-jev": "Open-Jev (DeBERTa-v3) — lightest",
};

// ─── Custom fine-tuned models ───────────────────────────────────────
// Registry generated by `npm run models:sync` from models.remote.json
// (published → HuggingFace repo ids) and the models/ directory (local
// payloads). Paths resolve relative to this package (src/.. or dist/..)
// so cwd never matters. Resolution order: local payload → HF repo → hub.

function localModelPath(alias: string): string | null {
  const entry = LOCAL_MODELS.find((m) => m.alias === alias);
  return entry ? join(dirname(fileURLToPath(import.meta.url)), "..", entry.path) : null;
}

function resolveModelId(model: string): string {
  return localModelPath(model)
    ?? REMOTE_MODELS.find((r) => r.alias === model)?.repo
    ?? MODEL_REPOS[model]
    ?? model;
}

// ─── Types ──────────────────────────────────────────────────────────

export interface JevClient {
  decide(state: string, questions: readonly Question[]): Promise<Answer[]>;
  models(): Promise<ModelInfo[]>;
  switch(model: ModelAlias): Promise<void>;
  dispose(): Promise<void>;
  readonly model: string;
  readonly mode: "native" | "http";
}

export interface CreateJevOptions extends Partial<JevConfig> {
  onProgress?: (info: { loaded: number; total: number }) => void;
}

// ─── Native transport (ARM64 Mac / Linux) ─────────────────────────

interface OpenJevRuntime {
  decide: (state: string, questions: unknown[]) => Promise<unknown[]>;
  dispose?: () => Promise<void>;
  runtime?: { model?: string; family?: string };
}

async function tryNativeLoad(
  model: string,
  dtype: string,
  onProgress?: (info: { loaded: number; total: number }) => void,
): Promise<OpenJevRuntime | null> {
  try {
    // Local fine-tunes: fail with a clear message if the registered
    // directory is gone (stale generated registry vs gitignored payload).
    const localDir = localModelPath(model);
    if (localDir && !existsSync(join(localDir, "onnx"))) {
      console.warn(
        `warning: "${model}" is registered but ${localDir}/onnx is missing — ` +
        `retrain/package it (npm run pipeline) or refresh the registry (npm run models:sync)`,
      );
      return null;
    }

    // Dynamic import — fails silently on unsupported platforms
    // SAFETY: open-jev's typed generics don't match our generic runtime
    // interface; cast through unknown at this dynamic import boundary.
    const mod = (await import("open-jev")) as unknown as {
      OpenJev: { load: (opts: Record<string, unknown>) => Promise<OpenJevRuntime> };
    };

    const runtime = await mod.OpenJev.load({
      model: resolveModelId(model),
      device: "cpu",
      dtype,
      onProgress: onProgress
        ? (p: { status?: string; loaded?: number; total?: number }) => {
            if (p.loaded !== undefined && p.total !== undefined && p.total > 0) {
              onProgress({ loaded: p.loaded, total: p.total });
            }
          }
        : undefined,
    });

    return runtime;
  } catch {
    return null;
  }
}

function mapNativeAnswer(raw: Record<string, unknown>, question: Question): Answer {
  if (question.kind === "choice") {
    const choice = String(raw.choice ?? "");
    const confidence = Number(raw.confidence ?? 0);
    const probabilities = (raw.probabilities ?? {}) as Record<string, number>;

    return { kind: "choice", id: question.id, choice, confidence, probabilities };
  }

  if (question.kind === "noul") {
    return {
      kind: "noul",
      id: question.id,
      answer: Boolean(raw.answer),
      probability: Number(raw.probability ?? 0),
      confidence: Number(raw.confidence ?? 0),
    };
  }

  return {
    kind: "score",
    id: question.id,
    score: Number(raw.score ?? 0),
    normalized: Number(raw.normalized ?? 0),
    level: String(raw.level ?? ""),
    confidence: Number(raw.confidence ?? 0),
  };
}

// ─── HTTP transport (Docker / remote) ──────────────────────────────

// Map a JEV-schema question to open-jev's runtime shape (what choice()/noul()/score()
// produce). The HTTP server path (server.ts buildQuestion) does exactly this; the
// native path must match it or open-jev rejects "kind"/"prompt" questions.
function buildNativeQuestion(q: Question): Record<string, unknown> {
  if (q.kind === "choice") {
    return { type: "choice", instructions: q.prompt, options: q.options, descriptions: q.descriptions };
  }
  if (q.kind === "noul") {
    return { type: "noul", instructions: q.prompt };
  }
  return { type: "score", instructions: q.prompt, options: q.levels };
}

// ─── Model listing (client-free) ─────────────────────────────────────
// Pure registry data + a metadata-only cache probe per repo (OpenJev.info
// fetches JSON metadata, never weights). Listing models must never load a
// model — the old implementation constructed a full kev-0.6b client (~383 MB)
// just to read names.

async function probeCached(repoId: string, dtype: string): Promise<boolean> {
  try {
    const mod = (await import("open-jev")) as unknown as {
      OpenJev: { info: (opts: Record<string, unknown>) => Promise<{ isCached?: boolean }> };
    };
    const info = await mod.OpenJev.info({ model: repoId, device: "cpu", dtype });
    return info.isCached ?? false;
  } catch {
    return false; // metadata probe only — never worth failing a listing
  }
}

async function buildModelList(dtype: string): Promise<ModelInfo[]> {
  const results: ModelInfo[] = [];

  for (const [alias, repo] of Object.entries(MODEL_REPOS)) {
    results.push({
      alias,
      displayName: MODEL_DISPLAY_NAMES[alias] ?? alias,
      repo,
      family: alias.startsWith("kev") ? "kev" : "open-jev",
      cached: await probeCached(repo, dtype),
      downloadSizeBytes: MODEL_SIZES[alias] ?? 0,
    });
  }

  // Published custom models: listed as their HuggingFace repo (the local
  // payload, if any, is shadowed — one entry per model, hosted wins).
  for (const remote of REMOTE_MODELS) {
    const local = LOCAL_MODELS.find((l) => l.alias === remote.alias);
    results.push({
      alias: remote.alias,
      displayName: remote.displayName,
      repo: remote.repo,
      family: remote.family,
      cached: await probeCached(remote.repo, dtype),
      downloadSizeBytes: local?.sizeBytes ?? 0,
    });
  }

  // Local fine-tunes not yet published: listed only when their payload is
  // actually present (a fresh clone without gitignored models/ sees the
  // hub + published models only).
  const published = new Set<string>(REMOTE_MODELS.map((r) => r.alias));
  for (const local of LOCAL_MODELS) {
    if (published.has(local.alias)) continue;

    const dir = localModelPath(local.alias)!;
    if (!existsSync(join(dir, "onnx"))) continue;

    results.push({
      alias: local.alias,
      displayName: local.displayName,
      repo: local.path,
      family: local.family,
      cached: true, // the payload directory IS the cache
      downloadSizeBytes: local.sizeBytes,
    });
  }

  return results;
}

const HTTP_TIMEOUT_MS = 120_000;

async function httpDecide(
  url: string,
  state: string,
  questions: readonly Question[],
): Promise<Answer[]> {
  const body = JSON.stringify({ state, questions });

  let response: Response;
  try {
    response = await fetch(`${url.replace(/\/$/, "")}/decide`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body,
      signal: AbortSignal.timeout(HTTP_TIMEOUT_MS),
    });
  } catch (e) {
    throw new Error(
      `jev http ${url} unreachable (${(e as Error).name}: ${(e as Error).message}) — ` +
      `is the Docker/server running? Start it with: npx @amatelic/jev serve`,
    );
  }

  if (!response.ok) {
    throw new Error(`jev http ${response.status}: ${(await response.text()).slice(0, 200)}`);
  }

  // SAFETY: response validated against DecideResponseSchema — a garbage
  // body fails here, loudly, instead of surfacing as distant undefined errors.
  const parsed = (await response.json()) as unknown;

  if (!Value.Check(DecideResponseSchema, parsed)) {
    throw new Error(
      `jev http: malformed response from ${url} — expected DecideResponseSchema`,
    );
  }

  const answers = parsed.answers;
  if (answers.length !== questions.length) {
    throw new Error(
      `jev http: server returned ${answers.length} answers for ${questions.length} questions`,
    );
  }

  return answers;
}

// ─── Public API ─────────────────────────────────────────────────────

export async function createJev(options: CreateJevOptions = {}): Promise<JevClient> {
  const model = options.model ?? "kev-0.6b";
  const dtype = options.dtype ?? "q4";
  const mode = options.mode ?? "auto";
  const url = options.url ?? "http://localhost:9401";

  let nativeRuntime: OpenJevRuntime | null = null;
  let transport: "native" | "http" = "http";

  if (mode === "native" || mode === "auto") {
    nativeRuntime = await tryNativeLoad(model, dtype, options.onProgress);
  }

  if (nativeRuntime) {
    transport = "native";
  } else if (mode === "native") {
    throw new Error(
      `Native mode requested but open-jev failed to load (platform may not support it). ` +
      `Try mode: "http" with a Docker server, or install the ARM64 build of Node.js.`,
    );
  }

  const decide = async (state: string, questions: readonly Question[]): Promise<Answer[]> => {
    // Validate the request at the boundary
    const request = { state, questions: [...questions] };
    const errors = [...Value.Errors(DecideRequestSchema, request)];

    if (errors.length > 0) {
      const first = errors[0]!;

      throw new Error(`Invalid request at ${first.path}: ${first.message}`);
    }

    if (transport === "native" && nativeRuntime) {
      const rawAnswers = await nativeRuntime.decide(
        state,
        questions.map(buildNativeQuestion),
      );

      return questions.map((q, i) =>
        mapNativeAnswer((rawAnswers[i] ?? {}) as Record<string, unknown>, q),
      );
    }

    return httpDecide(url, state, questions);
  };

  const models = async (): Promise<ModelInfo[]> => buildModelList(dtype);

  let currentModel = model;

  const client: JevClient = {
    decide,
    models,
    get model() {
      return currentModel;
    },
    mode: transport,
    switch: async (newModel: ModelAlias): Promise<void> => {
      if (transport !== "native") {
        throw new Error(
          "switch() requires a native client — the HTTP server loads its model at startup; " +
          "restart it with a different --model",
        );
      }

      // Load the new runtime FIRST: on failure the client keeps serving the
      // current model instead of silently degrading to a dead HTTP fallback.
      const next = await tryNativeLoad(newModel, dtype, options.onProgress);
      if (!next) {
        throw new Error(`Failed to switch to ${newModel} — keeping ${currentModel}`);
      }

      await nativeRuntime?.dispose?.();
      nativeRuntime = next;
      currentModel = newModel;
    },
    dispose: async (): Promise<void> => {
      await nativeRuntime?.dispose?.();
      nativeRuntime = null;
    },
  };

  return client;
}

export async function listModels(): Promise<ModelInfo[]> {
  // Registry data + metadata probes only — no client, no model weights.
  return buildModelList("q4");
}

export async function modelInfo(model: ModelAlias): Promise<ModelInfo | null> {
  const models = await listModels();

  return models.find((m) => m.alias === model) ?? null;
}

export async function download(
  model: ModelAlias,
  options: { onProgress?: (info: { loaded: number; total: number }) => void } = {},
): Promise<void> {
  if (localModelPath(model) && existsSync(join(localModelPath(model)!, "onnx"))) {
    return; // local fine-tunes are already on disk — nothing to fetch
  }

  // Downloads go through the native runtime (that is the mechanism). Never
  // construct an HTTP client here — it would fetch nothing and report success.
  try {
    const mod = (await import("open-jev")) as unknown as {
      OpenJev: { load: (opts: Record<string, unknown>) => Promise<{ dispose?: () => Promise<void> }> };
    };
    const rt = await mod.OpenJev.load({
      model: resolveModelId(model),
      device: "cpu",
      dtype: "q4",
      onProgress: options.onProgress
        ? (p: { status?: string; loaded?: number; total?: number }) => {
            if (p.loaded !== undefined && p.total !== undefined && p.total > 0) {
              options.onProgress!({ loaded: p.loaded, total: p.total });
            }
          }
        : undefined,
    });
    await rt.dispose?.();
  } catch (e) {
    throw new Error(
      `download("${model}") failed — the native runtime is required (ARM64 Mac/Linux). ` +
      `On x64 machines use: bash scripts/fetch-hf-cache.sh ${resolveModelId(model).split("/").slice(0, 2).join("/")} ` +
      `(${(e as Error).message?.slice(0, 120)})`,
    );
  }
}

